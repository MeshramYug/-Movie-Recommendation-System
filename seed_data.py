def repopulate_database():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # Drop and recreate clean table with language column
    cursor.execute('DROP TABLE IF EXISTS movies')
    cursor.execute('''
        CREATE TABLE movies (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            clean_title TEXT,
            year INTEGER,
            genres TEXT NOT NULL,
            language TEXT DEFAULT 'English',
            director TEXT,
            cast TEXT,
            overview TEXT,
            vote_average REAL DEFAULT 7.0,
            vote_count INTEGER DEFAULT 1000,
            runtime INTEGER DEFAULT 120,
            poster_url TEXT,
            backdrop_url TEXT,
            trailer_url TEXT,
            certification TEXT DEFAULT 'PG-13',
            tagline TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    ''')

    for m in ALL_MOVIES:
        cursor.execute('''
            INSERT INTO movies (
                title, clean_title, year, genres, language, director, cast, overview,
                vote_average, vote_count, runtime, poster_url, backdrop_url,
                trailer_url, certification, tagline
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            m["title"], m["clean_title"], m["year"], m["genres"], m["language"],
            m["director"], m["cast"], m["overview"], m["vote_average"], m["vote_count"],
            m["runtime"], m["poster_url"], m["backdrop_url"], m["trailer_url"],
            m["certification"], m["tagline"]
        ))

    conn.commit()
    cursor.execute('SELECT COUNT(*), COUNT(DISTINCT language), MIN(year), MAX(year) FROM movies')
    cnt, langs, min_y, max_y = cursor.fetchone()
    print(f"Database successfully repopulated: {cnt} movies across {langs} languages spanning from {min_y} to {max_y}!")
    conn.close()

if __name__ == '__main__':
    repopulate_database()

